for loc in locales:
    path = f'content/i18n/{loc}.json'
    with open(path, 'r', encoding='utf-8') as f:
        data = json.load(f)

    if 'aboutPage' not in data:
        data['aboutPage'] = {}

    # Add cert categories
    if 'certCats' not in data['aboutPage']:
        data['aboutPage']['certCats'] = {}
    for cat_id, translations in cert_cats.items():
        data['aboutPage']['certCats'][cat_id] = translations[loc]

    # Add cert names
    if 'certNames' not in data['aboutPage']:
        data['aboutPage']['certNames'] = {}
    for cert_id, translations in cert_names.items():
        data['aboutPage']['certNames'][cert_id] = translations[loc]

    with open(path, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print(f'{loc}: done')

print('All done')
